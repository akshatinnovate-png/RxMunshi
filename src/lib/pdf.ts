'use client';
// Printable PDFs (jsPDF): expiry return slip, inspection pack, H1 register.
// jsPDF's built-in fonts have no ₹ glyph, so amounts print as "Rs.".
import { jsPDF } from 'jspdf';
import type { DB, H1Entry, Shop } from '@/core/types';
import type { ReturnSlip } from '@/data/actions';
import type { Check } from '@/core/compliance';
import { formatDate, groupIN } from '@/core/util';
import { bucketOf, onShelf } from '@/core/expiry';

const rs = (n: number) => `Rs. ${groupIN(n, 2)}`;
type Col = { h: string; w: number; align?: 'right' };

function table(doc: jsPDF, x: number, y: number, cols: Col[], rows: string[][], pageH = 285): number {
  const rowH = 6.2;
  const header = () => {
    doc.setFillColor(27, 27, 29);
    doc.rect(x, y, cols.reduce((s, c) => s + c.w, 0), rowH, 'F');
    doc.setTextColor(255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    let cx = x;
    for (const c of cols) {
      doc.text(c.h.toUpperCase(), c.align === 'right' ? cx + c.w - 1.5 : cx + 1.5, y + 4.2, { align: c.align === 'right' ? 'right' : 'left' });
      cx += c.w;
    }
    doc.setTextColor(20);
    doc.setFont('helvetica', 'normal');
    y += rowH;
  };
  header();
  doc.setFontSize(8.5);
  for (const r of rows) {
    if (y > pageH - 12) {
      doc.addPage();
      y = 16;
      header();
    }
    let cx = x;
    r.forEach((cell, i) => {
      const c = cols[i];
      const t = doc.splitTextToSize(String(cell ?? ''), c.w - 3)[0] ?? '';
      doc.text(t, c.align === 'right' ? cx + c.w - 1.5 : cx + 1.5, y + 4.2, { align: c.align === 'right' ? 'right' : 'left' });
      cx += c.w;
    });
    doc.setDrawColor(200);
    doc.setLineDashPattern([0.8, 0.8], 0);
    doc.line(x, y + rowH, cx, y + rowH);
    doc.setLineDashPattern([], 0);
    y += rowH;
  }
  return y;
}

function letterhead(doc: jsPDF, shop: Shop, title: string) {
  doc.setFillColor(233, 79, 191);
  doc.rect(14, 12, 4, 4, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(20);
  doc.text(shop.name, 21, 16);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(`${shop.address}, ${shop.city} · Retail DL ${shop.drug_license_no} · GSTIN ${shop.gstin}`, 21, 21);
  doc.text(`Registered pharmacist: ${shop.pharmacist_name} (${shop.pharmacist_reg_no})`, 21, 25.5);
  doc.setLineWidth(0.6);
  doc.line(14, 29, 196, 29);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(title, 14, 37);
  doc.setFont('helvetica', 'normal');
}

export function returnSlipPDF(slip: ReturnSlip, shop: Shop, today: string): Blob {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  letterhead(doc, shop, 'Expiry Return Slip');
  doc.setFontSize(9.5);
  doc.text(`Slip no. ${slip.slip_no}`, 14, 44);
  doc.text(`Date ${formatDate(today)}`, 196, 44, { align: 'right' });
  doc.text(`To: ${slip.distributor_name}`, 14, 51);
  doc.text(`Wholesale licence (Form 20B/21B): ${slip.wholesaler?.license_no ?? '—'}`, 14, 56);
  if (slip.wholesaler) doc.text(`Credit terms: ${slip.wholesaler.credit_pct}% of cost · return window ${slip.wholesaler.return_window_days} days after expiry`, 14, 61);
  const y = table(
    doc,
    14,
    68,
    [
      { h: '#', w: 8 },
      { h: 'Medicine', w: 52 },
      { h: 'Batch', w: 26 },
      { h: 'Expiry', w: 24 },
      { h: 'Qty', w: 14, align: 'right' },
      { h: 'Cost/pack', w: 26, align: 'right' },
      { h: 'Claim', w: 32, align: 'right' },
    ],
    slip.lines.map((l, i) => [String(i + 1), l.batch.medicine_name, l.batch.batch_no, formatDate(l.batch.expiry_date), String(l.qty), rs(l.batch.cost_inr), rs(l.claim)]),
  );
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`Total claim ${rs(slip.total)}`, 196, y + 8, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(
    doc.splitTextToSize(
      'The above expired / near-expiry stock is returned to the supplying licensed wholesaler for credit. It has been removed from saleable stock. Please acknowledge receipt and issue a credit note against this slip number.',
      182,
    ),
    14,
    y + 18,
  );
  doc.text('For the retailer', 14, y + 42);
  doc.text('Received by (wholesaler)', 140, y + 42);
  doc.line(14, y + 38, 70, y + 38);
  doc.line(140, y + 38, 196, y + 38);
  doc.setFontSize(7.5);
  doc.setTextColor(120);
  doc.text('Generated by RxMunshi · B2B record-keeping software · does not sell or deliver medicines', 14, 290);
  return doc.output('blob');
}

export function h1Rows(entries: H1Entry[]) {
  return [...entries]
    .sort((a, b) => (a.dispensed_date < b.dispensed_date ? 1 : -1))
    .map((e) => [formatDate(e.dispensed_date), e.patient_name, e.doctor_name, e.doctor_address || 'MISSING', e.drug_name, e.batch_no, String(e.qty)]);
}
const H1_COLS: Col[] = [
  { h: 'Date', w: 22 },
  { h: 'Patient', w: 28 },
  { h: 'Prescriber', w: 30 },
  { h: 'Prescriber address', w: 46 },
  { h: 'Drug', w: 26 },
  { h: 'Batch', w: 18 },
  { h: 'Qty', w: 12, align: 'right' },
];

export function inspectionPackPDF(db: DB, checks: Check[], score: number, today: string): Blob {
  const shop = db.shops[0];
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  letterhead(doc, shop, `Inspection pack · ${formatDate(today)}`);
  doc.setFontSize(10);
  doc.text(`Compliance score ${score}/100 (self-assessment by RxMunshi from the shop's own records)`, 14, 45);
  let y = table(
    doc,
    14,
    50,
    [
      { h: 'Check', w: 62 },
      { h: 'State', w: 18 },
      { h: 'Detail', w: 102 },
    ],
    checks.map((c) => [c.title, c.state.toUpperCase(), c.detail]),
  );
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('1. Licences', 14, y + 10);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Retail drug licence ${shop.drug_license_no} · valid until ${formatDate(shop.license_valid_until)}`, 14, y + 16);
  doc.text(`Pharmacist ${shop.pharmacist_name} · reg. ${shop.pharmacist_reg_no} · valid until ${formatDate(shop.pharmacist_reg_valid_until)}`, 14, y + 21);

  doc.addPage();
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text(`2. Schedule H1 register (${db.schedule_h1_logs.length} entries, kept 3 years)`, 14, 16);
  doc.setFont('helvetica', 'normal');
  y = table(doc, 14, 21, H1_COLS, h1Rows(db.schedule_h1_logs));

  doc.addPage();
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('3. Expired and quarantined stock register', 14, 16);
  doc.setFont('helvetica', 'normal');
  const expired = db.inventory_batches.filter((b) => b.status === 'quarantined' || (b.status === 'active' && b.qty > 0 && bucketOf(b, today) === 'expired'));
  y = table(
    doc,
    14,
    21,
    [
      { h: 'Medicine', w: 52 },
      { h: 'Batch', w: 28 },
      { h: 'Expiry', w: 26 },
      { h: 'Qty', w: 14, align: 'right' },
      { h: 'Status', w: 30 },
      { h: 'Supplier', w: 32 },
    ],
    expired.map((b) => [b.medicine_name, b.batch_no, formatDate(b.expiry_date), String(b.qty), b.status === 'quarantined' ? 'QUARANTINED' : 'ON SHELF (fix)', b.distributor_name]),
  );
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('4. Expiry returns to licensed wholesalers', 14, y + 12);
  doc.setFont('helvetica', 'normal');
  y = table(
    doc,
    14,
    y + 17,
    [
      { h: 'Slip', w: 30 },
      { h: 'Wholesaler', w: 50 },
      { h: 'Medicine', w: 40 },
      { h: 'Claim', w: 30, align: 'right' },
      { h: 'Status', w: 32 },
    ],
    db.credit_notes.map((c) => [c.return_slip_no, c.distributor_name, c.medicine_name, rs(c.claim_amount_inr), c.status.toUpperCase()]),
  );

  doc.addPage();
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('5. Purchase bills index', 14, 16);
  doc.setFont('helvetica', 'normal');
  table(
    doc,
    14,
    21,
    [
      { h: 'Date', w: 26 },
      { h: 'Wholesaler', w: 62 },
      { h: 'Bill no.', w: 40 },
      { h: 'Lines', w: 16, align: 'right' },
      { h: 'Total', w: 38, align: 'right' },
    ],
    [...db.purchase_bills].sort((a, b) => (a.bill_date < b.bill_date ? 1 : -1)).map((b) => [formatDate(b.bill_date), b.distributor_name, b.bill_no, String(b.lines.length), rs(b.total_inr)]),
  );
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(7.5);
    doc.setTextColor(120);
    doc.text(`${shop.name} · inspection pack · page ${i} of ${pages} · on-shelf stock ${onShelf(db.inventory_batches).length} batches`, 14, 290);
    doc.setTextColor(20);
  }
  return doc.output('blob');
}

export function h1PDF(entries: H1Entry[], shop: Shop, today: string): Blob {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  letterhead(doc, shop, `Schedule H1 register · printed ${formatDate(today)}`);
  table(doc, 14, 44, H1_COLS, h1Rows(entries));
  return doc.output('blob');
}
